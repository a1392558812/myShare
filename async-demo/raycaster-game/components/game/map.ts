export const MAP_WIDTH = MAP[0].length

export const MAP_HEIGHT = MAP.length

/** 越界一律视为实心，避免射线或玩家逃出地图 */
export const cellAt = (x: number, y: number): number => {
  if (x < 0 || y < 0 || x >= MAP_WIDTH || y >= MAP_HEIGHT) return 1
  return MAP[y][x]
}

