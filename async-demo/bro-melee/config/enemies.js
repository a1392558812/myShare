/** 通过 id 取敌人类型 */
export const getEnemyType = (typeId) => {
  return ENEMY_TYPES.find((type) => type.id === typeId) || ENEMY_TYPES[0];
};

/**
 * 按等级挑选敌人类型（低等级只出野狼/土匪，高等级逐步出现术士/弓手/巨汉/忍者/和尚/刺客）
 * @param {Number} level 目标等级
 * @returns {Object} 敌人类型配置
 */
export const pickEnemyType = (level) => {
  const candidates = ENEMY_TYPES.filter((type) => {
    // 随从（奇遇入队）与首领都不参与常规刷新
    return !type.isBoss && !type.isCompanion && level >= type.minLevel;
  });
  const totalWeight = candidates.reduce((sum, type) => sum + type.weight, 0);
  let roll = Math.random() * totalWeight;
  for (let index = 0; index < candidates.length; index++) {
    roll -= candidates[index].weight;
    if (roll <= 0) {
      return candidates[index];
    }
  }
  return candidates[candidates.length - 1];
};
